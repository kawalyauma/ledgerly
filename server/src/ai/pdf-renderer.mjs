function escapePdfText(value) {
  return String(value ?? "")
    .replaceAll("\\", "\\\\")
    .replaceAll("(", "\\(")
    .replaceAll(")", "\\)")
    .replace(/[^\x20-\x7E]/g, "?");
}

function flattenContent(value, prefix = "", lines = []) {
  if (value == null) return lines;
  if (typeof value === "string" || typeof value === "number" || typeof value === "boolean") {
    lines.push(prefix ? `${prefix}: ${value}` : String(value));
    return lines;
  }
  if (Array.isArray(value)) {
    value.forEach((item, index) => flattenContent(item, prefix ? `${prefix} ${index + 1}` : String(index + 1), lines));
    return lines;
  }
  if (typeof value === "object") {
    for (const [key, item] of Object.entries(value)) {
      const label = String(key).replaceAll("_", " ").replace(/\b\w/g, (char) => char.toUpperCase());
      flattenContent(item, prefix ? `${prefix} · ${label}` : label, lines);
    }
  }
  return lines;
}

function wrapLine(text, width = 88) {
  const words = String(text).split(/\s+/).filter(Boolean);
  if (!words.length) return [""];
  const lines = [];
  let current = "";
  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word;
    if (candidate.length <= width) current = candidate;
    else {
      if (current) lines.push(current);
      current = word.length > width ? word.slice(0, width) : word;
    }
  }
  if (current) lines.push(current);
  return lines;
}

function pageStream(lines) {
  const commands = ["BT", "/F1 10 Tf", "50 790 Td", "13 TL"];
  for (const line of lines) commands.push(`(${escapePdfText(line)}) Tj`, "T*");
  commands.push("ET");
  return commands.join("\n");
}

function buildPdf(pages) {
  const objects = [];
  const add = (body) => { objects.push(body); return objects.length; };
  const catalogId = add("");
  const pagesId = add("");
  const fontId = add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");
  const pageIds = [];
  for (const page of pages) {
    const stream = pageStream(page);
    const streamId = add(`<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`);
    const pageId = add(`<< /Type /Page /Parent ${pagesId} 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 ${fontId} 0 R >> >> /Contents ${streamId} 0 R >>`);
    pageIds.push(pageId);
  }
  objects[catalogId - 1] = `<< /Type /Catalog /Pages ${pagesId} 0 R >>`;
  objects[pagesId - 1] = `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(" ")}] /Count ${pageIds.length} >>`;

  let output = "%PDF-1.4\n";
  const offsets = [0];
  objects.forEach((body, index) => {
    offsets[index + 1] = Buffer.byteLength(output);
    output += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xref = Buffer.byteLength(output);
  output += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= objects.length; i++) output += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
  output += `trailer\n<< /Size ${objects.length + 1} /Root ${catalogId} 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(output, "binary");
}

function provenanceFooter(document) {
  const source = document?.ai_provenance?.document ?? document?.ai_provenance;
  if (!source?.agent_name) return null;
  return `Originally generated by AI - ${source.agent_name} (${source.agent_role ?? "AI employee"})`;
}

async function organizationHeader(database, organizationId) {
  if (!database?.query) return [];
  const organization = await database.query(`SELECT id,name,base_currency FROM organizations WHERE id=$1`,[organizationId]).then((r)=>r.rows[0]??null).catch(()=>null);
  let profile=null;
  try {
    const exists=await database.query(`SELECT to_regclass('school_profiles') AS relation`);
    if(exists.rows[0]?.relation){
      profile=await database.query(`SELECT school_code,motto,physical_address,district_region,country,website,head_teacher_name,branding_json FROM school_profiles WHERE organization_id=$1`,[organizationId]).then((r)=>r.rows[0]??null);
    }
  } catch { profile=null; }
  const lines=[];
  if(organization?.name)lines.push(String(organization.name));
  if(profile?.motto)lines.push(String(profile.motto));
  const location=[profile?.physical_address,profile?.district_region,profile?.country].filter(Boolean).join(", ");
  if(location)lines.push(location);
  if(profile?.school_code)lines.push(`School code: ${profile.school_code}`);
  if(profile?.website)lines.push(String(profile.website));
  if(lines.length)lines.push("");
  return lines;
}

export function createLocalPdfRenderer({ tenantStorage, database = null }) {
  if (!tenantStorage?.forOrganization) throw new TypeError("AI PDF renderer requires tenant storage");
  return async ({ document, context }) => {
    const storage = tenantStorage.forOrganization(context.organizationId);
    const contentLines = flattenContent(document.content);
    const header=await organizationHeader(database,context.organizationId);
    const lines = [
      ...header,
      String(document.title ?? "Ledgerly Document"),
      `${String(document.type ?? "document").replaceAll("_", " ")} · Version ${document.version ?? 1}`,
      "",
      ...contentLines,
    ];
    const footer = provenanceFooter(document);
    if (footer) lines.push("", footer);
    const wrapped = lines.flatMap((line) => wrapLine(line));
    const pages = [];
    for (let index = 0; index < wrapped.length; index += 52) pages.push(wrapped.slice(index, index + 52));
    if (!pages.length) pages.push([String(document.title ?? "Ledgerly Document")]);
    const bytes = buildPdf(pages);
    const ref = `ai/documents/${document.document_id}/v${document.version ?? 1}.pdf`;
    await storage.put(ref, bytes, {
      contentType: "application/pdf",
      custom: {
        document_id: document.document_id,
        document_version: String(document.version ?? 1),
        organization_id: context.organizationId,
      },
    });
    return { ref, size: bytes.length, contentType: "application/pdf" };
  };
}
