export async function ensureMobileSyncCoreSchema(database) {
  await database.query(`
    CREATE TABLE IF NOT EXISTS mobile_sync_devices (
      id text PRIMARY KEY,
      organization_id text NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      installation_id text NOT NULL,
      device_name text NOT NULL,
      platform text NOT NULL CHECK (platform IN ('android','ios')),
      device_model text, os_version text, app_version text NOT NULL,
      client_schema_version integer NOT NULL DEFAULT 1 CHECK (client_schema_version >= 1),
      status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','revoked')),
      last_push_sequence bigint NOT NULL DEFAULT 0 CHECK (last_push_sequence >= 0),
      last_seen_at timestamptz, revoked_at timestamptz,
      created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
      UNIQUE (organization_id,user_id,installation_id),
      UNIQUE (id,organization_id)
    );
    CREATE INDEX IF NOT EXISTS mobile_sync_devices_org_user_idx ON mobile_sync_devices(organization_id,user_id,status);
    CREATE TABLE IF NOT EXISTS mobile_offline_grants (
      id text PRIMARY KEY, device_id text NOT NULL REFERENCES mobile_sync_devices(id) ON DELETE CASCADE,
      token_hash text NOT NULL UNIQUE, issued_at timestamptz NOT NULL DEFAULT now(), expires_at timestamptz NOT NULL,
      last_used_at timestamptz, rotated_at timestamptz, revoked_at timestamptz
    );
    CREATE UNIQUE INDEX IF NOT EXISTS mobile_offline_grants_active_device_uq ON mobile_offline_grants(device_id) WHERE revoked_at IS NULL;
    CREATE INDEX IF NOT EXISTS mobile_offline_grants_expiry_idx ON mobile_offline_grants(expires_at,revoked_at);
    CREATE TABLE IF NOT EXISTS mobile_sync_device_schemas (
      device_id text NOT NULL REFERENCES mobile_sync_devices(id) ON DELETE CASCADE,
      module_key text NOT NULL, collection_key text NOT NULL, schema_version integer NOT NULL CHECK (schema_version >= 1),
      acknowledged_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(device_id,module_key,collection_key)
    );
    CREATE TABLE IF NOT EXISTS mobile_sync_record_versions (
      organization_id text NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      module_key text NOT NULL, collection_key text NOT NULL, record_id text NOT NULL,
      version bigint NOT NULL CHECK(version >= 1), deleted boolean NOT NULL DEFAULT false,
      server_updated_at timestamptz NOT NULL DEFAULT now(), last_device_id text REFERENCES mobile_sync_devices(id) ON DELETE SET NULL,
      PRIMARY KEY(organization_id,module_key,collection_key,record_id)
    );
    CREATE INDEX IF NOT EXISTS mobile_sync_record_versions_collection_idx ON mobile_sync_record_versions(organization_id,module_key,collection_key,server_updated_at,record_id);
    CREATE TABLE IF NOT EXISTS mobile_sync_tombstones (
      organization_id text NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      module_key text NOT NULL, collection_key text NOT NULL, record_id text NOT NULL,
      version bigint NOT NULL CHECK(version >= 1), deleted_at timestamptz NOT NULL DEFAULT now(),
      device_id text REFERENCES mobile_sync_devices(id) ON DELETE SET NULL,
      PRIMARY KEY(organization_id,module_key,collection_key,record_id)
    );
    CREATE INDEX IF NOT EXISTS mobile_sync_tombstones_retention_idx ON mobile_sync_tombstones(organization_id,module_key,collection_key,deleted_at);
    CREATE TABLE IF NOT EXISTS mobile_sync_changes (
      change_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      organization_id text NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      module_key text NOT NULL, collection_key text NOT NULL, record_id text NOT NULL,
      version bigint NOT NULL CHECK(version >= 1), operation text NOT NULL CHECK(operation IN ('upsert','delete')),
      payload_json text, changed_by text, device_id text REFERENCES mobile_sync_devices(id) ON DELETE SET NULL,
      changed_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS mobile_sync_changes_pull_idx ON mobile_sync_changes(organization_id,module_key,collection_key,change_id);
    CREATE INDEX IF NOT EXISTS mobile_sync_changes_changed_idx ON mobile_sync_changes(organization_id,changed_at,change_id);
    CREATE TABLE IF NOT EXISTS mobile_sync_batches (
      id text PRIMARY KEY, organization_id text NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      device_id text NOT NULL REFERENCES mobile_sync_devices(id) ON DELETE CASCADE, batch_uuid text NOT NULL, request_hash text NOT NULL,
      status text NOT NULL DEFAULT 'processing' CHECK(status IN ('processing','partial','completed','failed')),
      first_sequence bigint NOT NULL, last_sequence bigint NOT NULL, received_count integer NOT NULL DEFAULT 0,
      applied_count integer NOT NULL DEFAULT 0, conflict_count integer NOT NULL DEFAULT 0, rejected_count integer NOT NULL DEFAULT 0,
      blocked_count integer NOT NULL DEFAULT 0, retry_count integer NOT NULL DEFAULT 0, result_json text,
      received_at timestamptz NOT NULL DEFAULT now(), completed_at timestamptz, updated_at timestamptz NOT NULL DEFAULT now(),
      UNIQUE(device_id,batch_uuid)
    );
    CREATE INDEX IF NOT EXISTS mobile_sync_batches_recovery_idx ON mobile_sync_batches(device_id,status,received_at DESC);
    CREATE TABLE IF NOT EXISTS mobile_sync_operations (
      id text PRIMARY KEY, organization_id text NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      device_id text NOT NULL REFERENCES mobile_sync_devices(id) ON DELETE CASCADE,
      batch_id text NOT NULL REFERENCES mobile_sync_batches(id) ON DELETE CASCADE,
      operation_uuid text NOT NULL, request_hash text NOT NULL, sequence_number bigint NOT NULL CHECK(sequence_number >= 1),
      module_key text NOT NULL, collection_key text NOT NULL, record_id text NOT NULL,
      operation_kind text NOT NULL CHECK(operation_kind IN ('upsert','delete')), schema_version integer NOT NULL CHECK(schema_version >= 1),
      base_version bigint NOT NULL DEFAULT 0 CHECK(base_version >= 0), client_timestamp timestamptz NOT NULL, payload_json text,
      dependencies_json text NOT NULL DEFAULT '[]', status text NOT NULL DEFAULT 'received' CHECK(status IN ('received','applied','duplicate','conflict','blocked','rejected')),
      retryable boolean NOT NULL DEFAULT true, server_version bigint, result_json text, error_code text, error_message text,
      attempts integer NOT NULL DEFAULT 0, received_at timestamptz NOT NULL DEFAULT now(), processed_at timestamptz,
      UNIQUE(device_id,operation_uuid), UNIQUE(device_id,sequence_number)
    );
    CREATE INDEX IF NOT EXISTS mobile_sync_operations_batch_idx ON mobile_sync_operations(batch_id,sequence_number);
    CREATE INDEX IF NOT EXISTS mobile_sync_operations_recovery_idx ON mobile_sync_operations(device_id,status,sequence_number);
    CREATE TABLE IF NOT EXISTS mobile_sync_conflicts (
      id text PRIMARY KEY, organization_id text NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      device_id text NOT NULL REFERENCES mobile_sync_devices(id) ON DELETE CASCADE,
      batch_id text NOT NULL REFERENCES mobile_sync_batches(id) ON DELETE CASCADE, operation_id text NOT NULL,
      module_key text NOT NULL, collection_key text NOT NULL, record_id text NOT NULL,
      client_base_version bigint NOT NULL, server_version bigint NOT NULL, client_payload_json text, server_payload_json text,
      resolution text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS mobile_sync_conflicts_record_idx ON mobile_sync_conflicts(organization_id,module_key,collection_key,record_id,created_at DESC);
    CREATE TABLE IF NOT EXISTS mobile_sync_pull_state (
      device_id text NOT NULL REFERENCES mobile_sync_devices(id) ON DELETE CASCADE,
      module_key text NOT NULL, collection_key text NOT NULL, last_acked_change_id bigint NOT NULL DEFAULT 0 CHECK(last_acked_change_id >= 0),
      updated_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(device_id,module_key,collection_key)
    );
    CREATE TABLE IF NOT EXISTS mobile_sync_pull_deliveries (
      id text PRIMARY KEY, organization_id text NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      device_id text NOT NULL REFERENCES mobile_sync_devices(id) ON DELETE CASCADE, request_id text NOT NULL,
      module_key text NOT NULL, collection_key text NOT NULL, from_change_id bigint NOT NULL DEFAULT 0, to_change_id bigint NOT NULL DEFAULT 0,
      payload_count integer NOT NULL DEFAULT 0, status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','acknowledged')),
      created_at timestamptz NOT NULL DEFAULT now(), acknowledged_at timestamptz,
      UNIQUE(device_id,request_id,module_key,collection_key)
    );
    CREATE INDEX IF NOT EXISTS mobile_sync_pull_pending_idx ON mobile_sync_pull_deliveries(device_id,status,created_at);
    CREATE TABLE IF NOT EXISTS mobile_sync_bootstraps (
      id text PRIMARY KEY, organization_id text NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      device_id text NOT NULL REFERENCES mobile_sync_devices(id) ON DELETE CASCADE,
      status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','acknowledged','superseded')),
      watermarks_json text NOT NULL, collection_count integer NOT NULL DEFAULT 0,
      created_at timestamptz NOT NULL DEFAULT now(), acknowledged_at timestamptz
    );
    CREATE INDEX IF NOT EXISTS mobile_sync_bootstrap_device_idx ON mobile_sync_bootstraps(device_id,status,created_at DESC);
    CREATE TABLE IF NOT EXISTS mobile_sync_events (
      id text PRIMARY KEY, organization_id text NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      device_id text REFERENCES mobile_sync_devices(id) ON DELETE SET NULL, user_id text,
      event_type text NOT NULL, batch_id text, operation_id text, details_json text, created_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS mobile_sync_events_device_idx ON mobile_sync_events(organization_id,device_id,created_at DESC);
    CREATE INDEX IF NOT EXISTS mobile_sync_events_type_idx ON mobile_sync_events(organization_id,event_type,created_at DESC);
  `);
}
